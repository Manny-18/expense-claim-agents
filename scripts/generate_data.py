def line(line_id, category, vendor, date, amount, city, **kw):
    base = dict(line_id=line_id, category=category, vendor=vendor, expense_date=date,
                amount=float(amount), city=city, description="", tax_amount=0.0,
                gstin=None, invoice_no=None, receipt_available=True, receipt_legible=True,
                missing_receipt_declaration=False, invoice_name="employee", nights=None,
                attendees=[], client_attendee_named=False, contains_alcohol=False,
                alcohol_amount=0.0, distance_km=None, vehicle_type=None, travel_class=None,
                sector_hours=None, journey_start_hour=None, journey_purpose=None,
                justification="", pre_approved=False, booked_via_travel_desk=False,
                client_rechargeable=False, engagement_code=None)
    base.update(kw)
    return base


