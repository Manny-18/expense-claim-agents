def make_gstin(state: str, pan_core: str, entity: str = "1") -> str:
    """Build a structurally and checksum valid GSTIN."""
    body = f"{state}{pan_core}{entity}Z"
    factor, total = 2, 0
    for i in reversed(range(14)):
        product = factor * CP.index(body[i])
        factor = 1 if factor == 2 else 2
        total += (product // 36) + (product % 36)
    return body + CP[(36 - (total % 36)) % 36]


